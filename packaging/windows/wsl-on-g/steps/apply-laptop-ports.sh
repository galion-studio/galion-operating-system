# Records the laptop port choice. Does not start Galion Research and
# does not start a HORBM preview. Does not change the Pi 5 desktop entry,
# which still sets PORT=8787 for the seed binary.

set -euo pipefail

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
# shellcheck disable=SC1091
. "$SCRIPT_DIR/../pins.env"

DRY=0
DEST_ROOT=

usage() {
  cat <<'EOF'
usage: apply-laptop-ports.sh [--dry-run | --dest-root DIR]

Writes /etc/profile.d/galion-research-port.sh. PORT is not exported.
The Node desk is started later with PORT set to GALION_RESEARCH_PORT.
EOF
}

while [ "$#" -gt 0 ]; do
  case $1 in
    --dry-run) DRY=1 ;;
    --dest-root)
      shift
      if [ "$#" -eq 0 ]; then
        printf 'refused: missing value for --dest-root\n' >&2
        exit 2
      fi
      DEST_ROOT=$1
      ;;
    -h|--help) usage; exit 0 ;;
    *)
      printf 'refused: unknown argument: %s\n' "$1" >&2
      exit 2
      ;;
  esac
  shift
done

if [ "$DRY" -eq 1 ] && [ -n "$DEST_ROOT" ]; then
  printf 'refused: use either --dry-run or --dest-root\n' >&2
  exit 2
fi

: "${GALION_RESEARCH_PORT:?}"
: "${GALION_HORBM_PREVIEW_PORT:?}"

body=$(cat <<EOF
# Generated by apply-laptop-ports.sh.
# Does not set PORT. The Pi 5 desktop entry sets PORT=8787 for its seed.
# Start the Node research desk with: PORT=${GALION_RESEARCH_PORT} npm start
export GALION_RESEARCH_PORT=${GALION_RESEARCH_PORT}
export GALION_HORBM_PREVIEW_PORT=${GALION_HORBM_PREVIEW_PORT}
EOF
)

if [ "$DRY" -eq 1 ]; then
  printf 'dry-run: GALION_RESEARCH_PORT=%s\n' "$GALION_RESEARCH_PORT"
  printf 'dry-run: GALION_HORBM_PREVIEW_PORT=%s\n' "$GALION_HORBM_PREVIEW_PORT"
  printf 'dry-run: does not start the Node research desk\n'
  printf 'dry-run: does not start a HORBM preview\n'
  printf 'dry-run: does not export PORT\n'
  exit 0
fi

if [ -n "$DEST_ROOT" ]; then
  dest=${DEST_ROOT%/}/etc/profile.d/galion-research-port.sh
else
  if [ "$(id -u)" -ne 0 ]; then
    printf 'refused: writing /etc/profile.d needs root\n' >&2
    exit 1
  fi
  dest=/etc/profile.d/galion-research-port.sh
fi

mkdir -p -- "$(dirname -- "$dest")"
printf '%s\n' "$body" >"$dest"
printf 'wrote %s\n' "$dest"
